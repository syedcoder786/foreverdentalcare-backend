-- Dental clinic schema. Written in portable SQL (PostgreSQL primary; H2 PostgreSQL-mode for tests).
-- All TIMESTAMPs are stored in UTC (TIMESTAMP WITH TIME ZONE). Appointment date/time columns are
-- clinic-local wall-clock values (DATE/TIME), interpreted using the configured clinic timezone.

CREATE TABLE admins (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    email       VARCHAR(150)  NOT NULL,
    password    VARCHAR(100)  NOT NULL,
    role        VARCHAR(20)   NOT NULL DEFAULT 'ADMIN',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_admins_email UNIQUE (email),
    CONSTRAINT ck_admins_role CHECK (role IN ('ADMIN'))
);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    BIGINT        NOT NULL,
    token_hash  VARCHAR(128)  NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_admin FOREIGN KEY (admin_id) REFERENCES admins (id) ON DELETE CASCADE
);
CREATE INDEX idx_refresh_tokens_admin ON refresh_tokens (admin_id);

CREATE TABLE patients (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(100)  NOT NULL,
    phone       VARCHAR(20)   NOT NULL,
    email       VARCHAR(150),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_patients_phone UNIQUE (phone)
);
CREATE INDEX idx_patients_full_name ON patients (full_name);

CREATE TABLE services (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                        VARCHAR(100)   NOT NULL,
    description                 VARCHAR(1000)  NOT NULL,
    details                     VARCHAR(2000),
    icon                        VARCHAR(50),
    consultation_fee            NUMERIC(10, 2),
    estimated_duration_minutes  INTEGER        NOT NULL,
    display_order               INTEGER        NOT NULL DEFAULT 0,
    active                      BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_services_name UNIQUE (name),
    CONSTRAINT ck_services_fee CHECK (consultation_fee IS NULL OR consultation_fee >= 0),
    CONSTRAINT ck_services_duration CHECK (estimated_duration_minutes > 0)
);
CREATE INDEX idx_services_active ON services (active);

CREATE TABLE appointments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id        BIGINT        NOT NULL,
    service_id        BIGINT        NOT NULL,
    appointment_date  DATE          NOT NULL,
    appointment_time  TIME          NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    message           VARCHAR(1000),
    -- TRUE while the appointment occupies its slot; NULL once cancelled (NULLs are distinct in UNIQUE).
    slot_active       BOOLEAN,
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_appointments_patient FOREIGN KEY (patient_id) REFERENCES patients (id),
    CONSTRAINT fk_appointments_service FOREIGN KEY (service_id) REFERENCES services (id),
    CONSTRAINT ck_appointments_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED')),
    -- COALESCE is essential: a CHECK only fails on FALSE, and (NULL = TRUE) evaluates to NULL.
    CONSTRAINT ck_appointments_slot_active CHECK (
        (status = 'CANCELLED' AND slot_active IS NULL)
        OR (status <> 'CANCELLED' AND COALESCE(slot_active, FALSE) = TRUE)
    ),
    -- Database-level guarantee: at most one active appointment per slot (single-dentist clinic).
    CONSTRAINT uk_appointments_active_slot UNIQUE (appointment_date, appointment_time, slot_active)
);
CREATE INDEX idx_appointments_date ON appointments (appointment_date);
CREATE INDEX idx_appointments_status ON appointments (status);
CREATE INDEX idx_appointments_patient ON appointments (patient_id);
CREATE INDEX idx_appointments_service ON appointments (service_id);

CREATE TABLE clinic_settings (
    id                     BIGINT        PRIMARY KEY,
    clinic_name            VARCHAR(150)  NOT NULL,
    address                VARCHAR(300)  NOT NULL,
    phone                  VARCHAR(20)   NOT NULL,
    whatsapp_number        VARCHAR(20),
    email                  VARCHAR(150),
    map_embed_url          VARCHAR(1000),
    opening_time           TIME          NOT NULL,
    closing_time           TIME          NOT NULL,
    break_start_time       TIME,
    break_end_time         TIME,
    working_days           VARCHAR(100)  NOT NULL,
    slot_duration_minutes  INTEGER       NOT NULL,
    booking_window_days    INTEGER       NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_settings_hours CHECK (closing_time > opening_time),
    CONSTRAINT ck_settings_slot CHECK (slot_duration_minutes BETWEEN 5 AND 240),
    CONSTRAINT ck_settings_window CHECK (booking_window_days BETWEEN 1 AND 365)
);
