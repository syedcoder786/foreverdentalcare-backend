-- Patient sign-in with a WhatsApp one-time code.

-- WhatsApp Cloud API settings, edited in Admin -> Settings (single row, id = 1).
CREATE TABLE whatsapp_settings (
    id                     BIGINT        PRIMARY KEY,
    enabled                BOOLEAN       NOT NULL DEFAULT FALSE,
    phone_number_id        VARCHAR(50),
    business_account_id    VARCHAR(50),
    access_token           VARCHAR(1000),
    otp_template_name      VARCHAR(100),
    otp_template_language  VARCHAR(20)   NOT NULL DEFAULT 'en_US',
    default_country_code   VARCHAR(4)    NOT NULL DEFAULT '91',
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL
);
INSERT INTO whatsapp_settings (id, enabled, otp_template_language, default_country_code, updated_at)
VALUES (1, FALSE, 'en_US', '91', CURRENT_TIMESTAMP);

-- One-time codes. Only an HMAC of the code is stored.
CREATE TABLE otp_challenges (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone       VARCHAR(20)   NOT NULL,
    code_hash   VARCHAR(128)  NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts    INT           NOT NULL DEFAULT 0,
    consumed    BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_otp_challenges_phone_created ON otp_challenges (phone, created_at);

-- Patient sessions (refresh tokens). Only a SHA-256 hash of the token is stored.
CREATE TABLE patient_refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id  BIGINT        NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    token_hash  VARCHAR(128)  NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_patient_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_patient_refresh_tokens_patient ON patient_refresh_tokens (patient_id);
