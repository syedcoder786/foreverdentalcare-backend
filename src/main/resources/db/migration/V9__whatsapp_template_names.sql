-- Reusable list of WhatsApp template names that the admin adds by hand.
CREATE TABLE whatsapp_template_names (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    language    VARCHAR(20)  NOT NULL DEFAULT 'en_US',
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_whatsapp_template_names UNIQUE (name, language)
);

-- Appointment messages are now added by the admin; drop the empty placeholder rows created in V8.
DELETE FROM whatsapp_templates WHERE purpose <> 'MARKETING' AND template_name IS NULL;
