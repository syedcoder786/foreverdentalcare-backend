-- ---------- Doctors ----------
CREATE TABLE doctors (
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name                     VARCHAR(100)   NOT NULL,
    slug                          VARCHAR(120)   NOT NULL,
    professional_title            VARCHAR(150)   NOT NULL,
    gender                        VARCHAR(20)    NOT NULL DEFAULT 'UNSPECIFIED',
    profile_image_url             VARCHAR(500),
    short_bio                     VARCHAR(500),
    biography                     VARCHAR(10000),
    -- JSON array: [{"degree": "...", "institution": "...", "year": "..."}]
    qualifications                VARCHAR(5000)  NOT NULL DEFAULT '[]',
    registration_number           VARCHAR(100),
    registration_authority        VARCHAR(200),
    -- Qualifications/registration are shown publicly only after an admin confirms they were verified.
    credentials_verified          BOOLEAN        NOT NULL DEFAULT FALSE,
    experience_years              INTEGER,
    consultation_fee              NUMERIC(10, 2),
    display_order                INTEGER        NOT NULL DEFAULT 0,
    active                        BOOLEAN        NOT NULL DEFAULT TRUE,
    featured                      BOOLEAN        NOT NULL DEFAULT TRUE,
    version                       BIGINT         NOT NULL DEFAULT 0,
    created_at                    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at                    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_doctors_slug UNIQUE (slug),
    CONSTRAINT ck_doctors_gender CHECK (gender IN ('FEMALE', 'MALE', 'UNSPECIFIED')),
    CONSTRAINT ck_doctors_fee CHECK (consultation_fee IS NULL OR consultation_fee >= 0),
    CONSTRAINT ck_doctors_experience CHECK (experience_years IS NULL OR experience_years BETWEEN 0 AND 80)
);
CREATE INDEX idx_doctors_active ON doctors (active);

CREATE TABLE doctor_specialties (
    doctor_id     BIGINT NOT NULL,
    specialty_id  BIGINT NOT NULL,
    CONSTRAINT pk_doctor_specialties PRIMARY KEY (doctor_id, specialty_id),
    CONSTRAINT fk_doctor_specialties_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT fk_doctor_specialties_specialty FOREIGN KEY (specialty_id) REFERENCES specialties (id) ON DELETE CASCADE
);

CREATE TABLE doctor_services (
    doctor_id   BIGINT NOT NULL,
    service_id  BIGINT NOT NULL,
    CONSTRAINT pk_doctor_services PRIMARY KEY (doctor_id, service_id),
    CONSTRAINT fk_doctor_services_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT fk_doctor_services_service FOREIGN KEY (service_id) REFERENCES services (id) ON DELETE CASCADE
);
CREATE INDEX idx_doctor_services_service ON doctor_services (service_id);

-- Independent weekly schedule per doctor: one row per weekday (active = works that day; inactive = weekly off).
CREATE TABLE doctor_availability (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id              BIGINT       NOT NULL,
    day_of_week            VARCHAR(10)  NOT NULL,
    start_time             TIME         NOT NULL,
    end_time               TIME         NOT NULL,
    break_start_time       TIME,
    break_end_time         TIME,
    slot_duration_minutes  INTEGER      NOT NULL,
    active                 BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_doctor_availability_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT uk_doctor_availability_day UNIQUE (doctor_id, day_of_week),
    CONSTRAINT ck_doctor_availability_day CHECK (day_of_week IN ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY')),
    CONSTRAINT ck_doctor_availability_time CHECK (end_time > start_time),
    CONSTRAINT ck_doctor_availability_slot CHECK (slot_duration_minutes BETWEEN 5 AND 240),
    CONSTRAINT ck_doctor_availability_break CHECK (
        (break_start_time IS NULL AND break_end_time IS NULL)
        OR (break_start_time IS NOT NULL AND break_end_time IS NOT NULL AND break_end_time > break_start_time))
);

-- Special working hours for a particular date (overrides that weekday's schedule for one doctor).
CREATE TABLE doctor_special_hours (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id              BIGINT       NOT NULL,
    special_date           DATE         NOT NULL,
    start_time             TIME         NOT NULL,
    end_time               TIME         NOT NULL,
    break_start_time       TIME,
    break_end_time         TIME,
    slot_duration_minutes  INTEGER      NOT NULL,
    note                   VARCHAR(200),
    CONSTRAINT fk_doctor_special_hours_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT uk_doctor_special_hours_date UNIQUE (doctor_id, special_date),
    CONSTRAINT ck_doctor_special_hours_time CHECK (end_time > start_time),
    CONSTRAINT ck_doctor_special_hours_slot CHECK (slot_duration_minutes BETWEEN 5 AND 240),
    CONSTRAINT ck_doctor_special_hours_break CHECK (
        (break_start_time IS NULL AND break_end_time IS NULL)
        OR (break_start_time IS NOT NULL AND break_end_time IS NOT NULL AND break_end_time > break_start_time))
);

-- Blocked time: whole day (start/end time NULL) or a time range on one date.
-- doctor_id NULL = clinic-wide holiday that applies to every doctor.
CREATE TABLE doctor_blocked_dates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id   BIGINT,
    block_date  DATE          NOT NULL,
    start_time  TIME,
    end_time    TIME,
    reason      VARCHAR(200),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_doctor_blocked_dates_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id) ON DELETE CASCADE,
    CONSTRAINT ck_doctor_blocked_dates_time CHECK (
        (start_time IS NULL AND end_time IS NULL) OR (start_time IS NOT NULL AND end_time IS NOT NULL AND end_time > start_time))
);
CREATE INDEX idx_doctor_blocked_dates_date ON doctor_blocked_dates (block_date, doctor_id);

