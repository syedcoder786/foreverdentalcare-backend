-- Marketing messages are only sent to patients who opted in (Meta policy).
ALTER TABLE patients ADD COLUMN whatsapp_opt_in BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE patients ADD COLUMN whatsapp_opt_in_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE whatsapp_campaigns (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id     BIGINT        REFERENCES whatsapp_templates (id) ON DELETE SET NULL,
    template_label  VARCHAR(100)  NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    total           INT           NOT NULL DEFAULT 0,
    sent            INT           NOT NULL DEFAULT 0,
    failed          INT           NOT NULL DEFAULT 0,
    created_by      VARCHAR(150),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_whatsapp_campaigns_created ON whatsapp_campaigns (created_at);
