-- WhatsApp message templates (automatic appointment messages and marketing campaigns) and patient marketing opt-in.

-- Which approved Meta template to send for each purpose, and what fills its placeholders.
-- header_params / body_params / button_params are JSON arrays of {"source": "...", "text": "..."}.
CREATE TABLE whatsapp_templates (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purpose            VARCHAR(40)   NOT NULL,
    label              VARCHAR(100)  NOT NULL,
    enabled            BOOLEAN       NOT NULL DEFAULT FALSE,
    template_name      VARCHAR(100),
    template_language  VARCHAR(20)   NOT NULL DEFAULT 'en_US',
    header_params      VARCHAR(4000) NOT NULL DEFAULT '[]',
    body_params        VARCHAR(4000) NOT NULL DEFAULT '[]',
    button_params      VARCHAR(4000) NOT NULL DEFAULT '[]',
    header_media_url   VARCHAR(1000),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_whatsapp_templates_purpose ON whatsapp_templates (purpose);

